/* ----
# Redirects
# 仅将已确认迁移的旧文章 URL 301 到对应正文，维护既有链接的可达性。
# 已删除且无替代内容的页面继续返回 404，不做日期路径跳首页的兜底。
# 输出根构建的 _redirects，供 Cloudflare Pages 解析；边缘匹配须在部署后验证。
---- */

'use strict';

const OLD_LINKS = [
  ['/2023/10/12/『原点』/', '/posts/1/'],
  ['/2024/07/12/『末班花火』/', '/posts/2/'],
  ['/2025/01/30/『Shamrock』/', '/posts/3/'],
  ['/2025/12/12/Q君与世界的外侧/', '/posts/5/'],
  ['/2025/12/31/『我们的时间从什么时候起停下来了』/', '/posts/6/'],
  ['/2026/01/14/1月14日/', '/posts/7/'],
  ['/2026/02/16/2026-02-16 除夕/', '/posts/8/'],
];

// 逐段编码，避免空格拆开规则字段，或路径中的 ?/# 被误认为查询/片段。
function encodePath(path) {
  return path.split('/').map(encodeURIComponent).join('/');
}

hexo.extend.filter.register('after_generate', function () {
  if (this.config.root && this.config.root !== '/') return;

  const routes = new Set(this.route.list());
  const seen = new Set();
  const lines = ['# Generated by scripts/redirects.js: exact legacy article URLs only'];
  for (const [from, to] of OLD_LINKS) {
    const source = encodePath(from);
    if (seen.has(source)) throw new Error('Duplicate legacy redirect: ' + source);
    if (!routes.has(to.slice(1) + 'index.html')) {
      throw new Error('Legacy redirect destination was not generated: ' + to);
    }
    seen.add(source);
    lines.push(source + ' ' + to + ' 301');
  }
  this.route.set('_redirects', lines.join('\n') + '\n');
});
